-- QUESTION 54: Use LAG() to compare a team's season wins with its previous season's wins.
WITH
	T_WIN AS (
		SELECT
			M.SEASON,
			T.TEAM_NAME,
			COUNT(M.WINNER_TEAM_ID) AS MATCHES_WIN
		FROM
			MATCHES M
			JOIN TEAMS T ON M.WINNER_TEAM_ID = T.TEAM_ID
		GROUP BY
			M.SEASON,
			T.TEAM_NAME
		ORDER BY
			M.SEASON ASC
	)
SELECT
	SEASON,
	TEAM_NAME,
	MATCHES_WIN,
	LAG(MATCHES_WIN) OVER (
		PARTITION BY
			TEAM_NAME
		ORDER BY
			SEASON
	) AS LG
FROM
	T_WIN
ORDER BY
	SEASON,
	TEAM_NAME ASC;

-- QUESTION 55: Calculate the year-over-year change in wins for each team.
WITH
	T_WIN AS (
		SELECT
			M.SEASON,
			T.TEAM_NAME,
			COUNT(M.WINNER_TEAM_ID) AS MATCHES_WIN
		FROM
			MATCHES M
			JOIN TEAMS T ON M.WINNER_TEAM_ID = T.TEAM_ID
		GROUP BY
			M.SEASON,
			T.TEAM_NAME
		ORDER BY
			M.SEASON ASC
	)
SELECT
	SEASON,
	TEAM_NAME,
	MATCHES_WIN,
	LAG(MATCHES_WIN) OVER (
		PARTITION BY
			TEAM_NAME
		ORDER BY
			SEASON
	) AS LAST_WIN,
	MATCHES_WIN - LAG(MATCHES_WIN) OVER (
		PARTITION BY
			TEAM_NAME
		ORDER BY
			SEASON
	) AS CHANGE
FROM
	T_WIN
ORDER BY
	SEASON,
	TEAM_NAME ASC;