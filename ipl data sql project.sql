CREATE TABLE MATCHES (
	MATCH_ID INT PRIMARY KEY,
	SEASON INT,
	MATCH_DATE DATE,
	CITY VARCHAR(50),
	VENUE VARCHAR(150),
	TEAM1_ID INT,
	TEAM2_ID INT,
	TOSS_WINNER_TEAM_ID INT,
	TOSS_DECISION VARCHAR(10),
	WINNER_TEAM_ID INT,
	LOSER_TEAM_ID INT,
	RESULT_TYPE VARCHAR(20),
	RESULT_MARGIN INT,
	TEAM1_SCORE INT,
	TEAM2_SCORE INT,
	PLAYER_OF_MATCH_ID INT,
	TEAM1_SIXES INT,
	TEAM2_SIXES INT,
	TEAM1_FOURS INT,
	TEAM2_FOURS INT,
	FOREIGN KEY (TEAM1_ID) REFERENCES TEAMS (TEAM_ID),
	FOREIGN KEY (TEAM2_ID) REFERENCES TEAMS (TEAM_ID),
	FOREIGN KEY (TOSS_WINNER_TEAM_ID) REFERENCES TEAMS (TEAM_ID),
	FOREIGN KEY (WINNER_TEAM_ID) REFERENCES TEAMS (TEAM_ID),
	FOREIGN KEY (LOSER_TEAM_ID) REFERENCES TEAMS (TEAM_ID),
	FOREIGN KEY (PLAYER_OF_MATCH_ID) REFERENCES PLAYERS (PLAYER_ID)
);

